const TABLE = { en, ar };

/* Missing Arabic falls back to English rather than to a raw key — a blank
   label is worse than an English one. */
export function translate(lang, key, vars) {
  let s = TABLE[lang]?.[key] ?? TABLE.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(v);
  return s;
}

export function readLang() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved && LANGS.includes(saved)) return saved;
    /* First visit: follow the browser. Most phones in Lebanon report ar-LB. */
    return (navigator.language || "en").toLowerCase().startsWith("ar") ? "ar" : "en";
  } catch {
    return "en";
  }
}
